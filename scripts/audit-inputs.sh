#!/usr/bin/env bash
# Deterministic inputs for the weekly `/tech-lead audit` (issue #38), so the
# agent reads facts instead of querying for them:
#
#   docs/costs.csv, docs/costs.md   copied from the bookkeeping branch, with totals
#   .agent-tmp/audit-ci.md          CI runs of the last 7 days that failed or were re-run
#   .agent-tmp/audit-issues.md      pipeline issues stuck > 3 days, and blocked ones
#
#   .agent-tmp/audit-actions.md     repeated actions, denials and re-reads from run digests (#84)
#
# Needs gh (GH_REPO set or run in the repo) and node. Never fails on missing data.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p .agent-tmp

since=$(date -u -d '7 days ago' +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -v-7d +%Y-%m-%dT%H:%M:%SZ)
stale=$(date -u -d '3 days ago' +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -v-3d +%Y-%m-%dT%H:%M:%SZ)

# Costs
if git fetch -q origin bookkeeping 2>/dev/null; then
	git show FETCH_HEAD:costs.csv > docs/costs.csv
	{
		echo '# Agent costs'
		echo
		echo 'Generated by the weekly audit from `docs/costs.csv` (`node scripts/costs.mjs summary`).'
		echo 'Estimated at API prices; not the subscription bill.'
		echo
		node scripts/costs.mjs summary docs/costs.csv
	} > docs/costs.md
else
	echo 'No bookkeeping branch yet; costs unchanged.' >&2
fi

# CI: failures and re-runs (a re-run that passed is a flaky-test candidate)
{
	echo "# CI runs since $since that failed or were re-run"
	echo
	gh run list --workflow ci.yml --limit 200 --created ">=$since" \
		--json databaseId,attempt,conclusion,headBranch,event,url,displayTitle \
		--jq '.[] | select(.attempt > 1 or .conclusion == "failure") |
			"- \(.conclusion) (attempt \(.attempt)) on `\(.headBranch)` (\(.event)): \(.displayTitle) \(.url)"'
} > .agent-tmp/audit-ci.md

# Issues: blocked, or in one pipeline state with no activity for 3 days
{
	echo "# Pipeline issues blocked, or unchanged since $stale"
	echo
	gh issue list --state open --limit 200 --json number,title,labels,updatedAt \
		--jq '.[] |
			{n: .number, t: .title, u: .updatedAt, s: ([.labels[].name | select(startswith("status:"))] | join(","))} |
			select(.s != "" and (.s == "status:blocked" or .u < "'"$stale"'")) |
			"- #\(.n) \(.t): `\(.s)`, last update \(.u)"'
} > .agent-tmp/audit-issues.md

# Agent actions: the digests agents.yml uploads (`agent-digest`) per run, last 7 days.
# Runs without one (older, expired, or failed before the step) are skipped.
rm -rf .agent-tmp/digests
mkdir -p .agent-tmp/digests
# List artifacts, not runs: the */30 schedule alone makes 336 agents.yml runs a week,
# most of them route-only no-ops without a digest.
for id in $(gh api "repos/${GH_REPO:-$(gh repo view --json nameWithOwner --jq .nameWithOwner)}/actions/artifacts?name=agent-digest&per_page=100" \
	--paginate --jq '.artifacts[] | select(.created_at >= "'"$since"'" and (.expired | not)) | .workflow_run.id' 2>/dev/null || true); do
	gh run download "$id" -n agent-digest -D ".agent-tmp/digests/$id" >/dev/null 2>&1 || true
done
node scripts/costs.mjs actions .agent-tmp/digests > .agent-tmp/audit-actions.md
